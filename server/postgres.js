export class PostgresDatabase {
  constructor(databaseUrl, {
    pool,
    maxConnections = 10,
    connectionTimeoutMs = 5000,
    idleTimeoutMs = 30_000,
    statementTimeoutMs = 10_000,
    transactionIdleTimeoutMs = 5000,
    ssl = false,
    initialize = true,
  } = {}) {
    validatePostgresUrl(databaseUrl);
    for (const [name, value, min, max] of [
      ['maxConnections', maxConnections, 1, 50],
      ['connectionTimeoutMs', connectionTimeoutMs, 100, 60_000],
      ['idleTimeoutMs', idleTimeoutMs, 1000, 600_000],
      ['statementTimeoutMs', statementTimeoutMs, 100, 60_000],
      ['transactionIdleTimeoutMs', transactionIdleTimeoutMs, 100, 60_000],
    ]) {
      if (!Number.isSafeInteger(value) || value < min || value > max) {
        throw new TypeError(`${name} must be an integer between ${min} and ${max}.`);
      }
    }
    this.dialect = 'postgres';
    this.statementTimeoutMs = statementTimeoutMs;
    this.transactionIdleTimeoutMs = transactionIdleTimeoutMs;
    this.transactionStorage = new AsyncLocalStorage();
    this.savepointCounter = 0;
    this.pool = pool ?? new Pool({
      connectionString: databaseUrl,
      max: maxConnections,
      connectionTimeoutMillis: connectionTimeoutMs,
      idleTimeoutMillis: idleTimeoutMs,
      allowExitOnIdle: false,
      application_name: 'systems-mapping',
      ...(ssl ? { ssl: { rejectUnauthorized: true } } : {}),
    });
    this.pool.on?.('error', () => {
      // Never include connection details or driver error objects in logs.
      console.error('The PostgreSQL connection pool reported an idle client error.');
    });
    this.ready = initialize ? initializePostgres(this) : Promise.resolve();
  }

  get isTransaction() {
    return Boolean(this.transactionStorage.getStore());
  }

  async query(sql, parameters = []) {
    await this.ready;
    const target = this.transactionStorage.getStore() ?? this.pool;
    const result = await target.query(compilePostgresSql(sql), parameters);
    return {
      rows: result.rows.map(normalizeRow),
      rowCount: result.rowCount ?? 0,
    };
  }

  prepare(sql) {
    return {
      all: async (...parameters) => (await this.query(sql, parameters)).rows,
      get: async (...parameters) => (await this.query(sql, parameters)).rows[0],
      run: async (...parameters) => {
        const result = await this.query(sql, parameters);
        return { changes: result.rowCount };
      },
    };
  }

  async exec(sql) {
    await this.ready;
    const target = this.transactionStorage.getStore() ?? this.pool;
    await target.query(sql);
  }

  async transaction(callback) {
    await this.ready;
    const activeClient = this.transactionStorage.getStore();
    if (activeClient) {
      const savepoint = `systems_mapping_${this.savepointCounter += 1}`;
      await activeClient.query(`SAVEPOINT ${savepoint}`);
      try {
        const result = await callback();
        await activeClient.query(`RELEASE SAVEPOINT ${savepoint}`);
        return result;
      } catch (error) {
        await activeClient.query(`ROLLBACK TO SAVEPOINT ${savepoint}`);
        await activeClient.query(`RELEASE SAVEPOINT ${savepoint}`);
        throw error;
      }
    }

    const client = await this.pool.connect();
    try {
      await client.query('BEGIN');
      await client.query(`SET LOCAL statement_timeout = '${this.statementTimeoutMs}ms'`);
      await client.query(`SET LOCAL idle_in_transaction_session_timeout = '${this.transactionIdleTimeoutMs}ms'`);
      const result = await this.transactionStorage.run(client, callback);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally {
      client.release();
    }
  }

  async advisoryTransactionLock(scope) {
    const client = this.transactionStorage.getStore();
    if (!client) throw new Error('A PostgreSQL advisory transaction lock requires an active transaction.');
    await client.query('SELECT pg_advisory_xact_lock(hashtext($1))', [scope]);
  }

  async healthCheck() {
    const result = await this.query('SELECT 1 AS ok');
    return result.rows[0]?.ok === 1;
  }

  async close() {
    await this.ready.catch(() => {});
    await this.pool.end();
  }
}

export function openPostgresDatabase(databaseUrl, options = {}) {
  return new PostgresDatabase(databaseUrl, options);
}
