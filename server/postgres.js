function normalizeValue(value) {
  if (value instanceof Date) return value.toISOString();
  return value;
}

function normalizeRow(row) {
  return Object.fromEntries(Object.entries(row).map(([key, rawValue]) => {
    const value = normalizeValue(rawValue);
    if (typeof value === 'string' && /^-?\d+$/.test(value)) {
      const numeric = Number(value);
      if (Number.isSafeInteger(numeric) && [
        'id', 'count', 'rowCount', 'correlationCount', 'oldestAt', 'newestAt',
        'createdAt', 'expiresAt', 'revokedAt', 'recordedAt', 'revision', 'stage',
        'updatedAt', 'reviewedAt', 'decidedAt', 'fromRevision', 'toRevision', 'sessionCount',
      ].includes(key)) return [key, numeric];
    }
    return [key, value];
  }));
}

export function validatePostgresUrl(databaseUrl) {
  if (typeof databaseUrl !== 'string' || databaseUrl.length < 1 || databaseUrl.length > 8192) {
    throw new TypeError('DATABASE_URL must be a non-empty PostgreSQL connection URL.');
  }
  let parsed;
  try {
    parsed = new URL(databaseUrl);
  } catch {
    throw new TypeError('DATABASE_URL must be a valid PostgreSQL connection URL.');
  }
  if (!['postgres:', 'postgresql:'].includes(parsed.protocol) || !parsed.hostname || !parsed.pathname.slice(1)) {
    throw new TypeError('DATABASE_URL must use postgres:// or postgresql:// and name a database.');
  }
  return parsed;
}

export function compilePostgresSql(source) {
  let parameter = 0;
  return source
    .replace(/LIMIT\s+-1\s+OFFSET\s+\?/gi, 'OFFSET ?')
    .replace(/\?/g, () => `$${parameter += 1}`)
    .replace(/\bAS\s+([A-Za-z][A-Za-z0-9]*)/gi, (_match, alias) => `AS "${alias}"`);
}

function migratedJsonDocument(value) {
  const parsed = typeof value === 'string' ? JSON.parse(value) : value;
  const original = JSON.stringify(parsed);
  const migrated = JSON.stringify(migrateScaleIds(parsed));
  return migrated === original ? null : migrated;
}

function serializedJsonDocument(value) {
  return typeof value === 'string' ? value : JSON.stringify(value);
}

