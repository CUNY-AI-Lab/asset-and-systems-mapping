test('account changes hide imported private maps and leave stored recovery bytes untouched', async () => {
  const storage = recoveryStorage(localStorage, cacheKey), project = createDefaultProject(); project.title = 'Private recovery fixture';
  const raw = JSON.stringify({ version: 1, entries: [{ scope: 'account', key: STORAGE_KEY, value: serializeProject(project) }] });
  await stageBrowserSnapshot(raw, storage, localStorage);
  const before = Object.entries(localStorage);
  let signedIn = account;
  vi.stubGlobal('fetch', vi.fn(async () => Response.json({ account: signedIn })));
  render(<BrowserRecovery mode="destination" />);
  fireEvent.click(await screen.findByRole('button', { name: /Review backup from/ }));
  await screen.findByRole('heading', { name: 'Private recovery fixture' });
  signedIn = { ...account, cacheKey: 'bbbbbbbb-bbbb-4bbb-bbbb-bbbbbbbbbbbb' };
  await act(async () => { window.dispatchEvent(new Event('focus')); });
  await waitFor(() => expect(screen.queryByRole('heading', { name: 'Private recovery fixture' })).not.toBeInTheDocument());
  expect(screen.getByText('Account access changed. Reopen recovery after signing in.')).toBeInTheDocument();
  expect(Object.entries(localStorage)).toEqual(before);
  expect(fetch.mock.calls.every(([path]) => path === '/api/cloud/account')).toBe(true);
});
