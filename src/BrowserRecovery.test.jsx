test('reopening a backup preserves a later destination preference before allowing replacement', async () => {
  const storage = recoveryStorage(localStorage, cacheKey);
  const raw = JSON.stringify({ version: 1, entries: [{ scope: 'device', key: 'systems-mapping.sidebar-width', value: '300' }] });
  localStorage.setItem('systems-mapping.sidebar-width', '400');
  await stageBrowserSnapshot(raw, storage, localStorage);
  localStorage.setItem('systems-mapping.sidebar-width', '450');
  vi.stubGlobal('fetch', vi.fn(async () => Response.json({ account })));
  render(<BrowserRecovery mode="destination" />);
  fireEvent.click(await screen.findByRole('button', { name: /Review backup from/ }));
  const button = await screen.findByRole('button', { name: 'Use incoming preference' });
  await waitFor(() => expect(button).toBeEnabled());
  fireEvent.click(button);
  await waitFor(() => expect(localStorage.getItem('systems-mapping.sidebar-width')).toBe('300'));
  expect(stagedBrowserSnapshots(storage).flatMap(entry => entry.conflicts.map(item => item.value)).sort()).toEqual(['400', '450']);
});
test('a damaged archive leaves restoration disabled while the verified in-memory backup can still be downloaded', async () => {
  const storage = recoveryStorage(localStorage, cacheKey);
  const raw = JSON.stringify({ version: 1, entries: [{ scope: 'device', key: 'systems-mapping.theme', value: 'dark' }] });
  localStorage.setItem('systems-mapping.theme', 'light');
  const { key } = await stageBrowserSnapshot(raw, storage, localStorage);
  storage.setItem(key, 'damaged original archive');
  const before = Object.entries(localStorage);
  vi.stubGlobal('fetch', vi.fn(async path => path.endsWith('/issue') ? Response.json({ token: 'a'.repeat(64), expiresAt: Date.now() + 120000 })
    : path.endsWith('/consume') ? Response.json({ verified: true }) : Response.json({ account })));
  vi.spyOn(window, 'open').mockReturnValue({ close: vi.fn(), location: { href: '' } });
  render(<BrowserRecovery mode="destination" />);
  const start = await screen.findByRole('button', { name: 'Read copies from the other address' });
  await waitFor(() => expect(start).toBeEnabled()); fireEvent.click(start);
  await waitFor(() => expect(receiveRecovery).toHaveBeenCalledOnce());
  const channel = receiveRecovery.mock.calls[0][0];
  await act(async () => { await channel.onSnapshot({ raw, fingerprint: await recoveryFingerprint(raw), receipt: 'b'.repeat(64), nonce: channel.nonce }); });
  expect(await screen.findByRole('alert')).toHaveTextContent('The backup could not be saved safely');
  expect(screen.getByRole('button', { name: 'Use incoming preference' })).toBeDisabled();
  expect(Object.entries(localStorage)).toEqual(before);
  fireEvent.click(screen.getByRole('button', { name: 'Download private browser backup' }));
  await waitFor(() => expect(downloadBlob).toHaveBeenCalledOnce());
  expect(Object.entries(localStorage)).toEqual(before);
});
