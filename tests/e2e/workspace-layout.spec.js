import { expect, test, scanAccessibility, assertNoAccessibilityViolations, captureSourceRenderedScreenshot } from './support/test.js';
import { serializedEastHarlemDisabilityProject } from './fixtures/east-harlem-disability-project.js';
import { STORAGE_KEY } from '../../src/projectLibrary.js';

test('map fills the viewport and sidebar resizes, wraps and collapses at every breakpoint', async ({ page, makeAxeBuilder }, testInfo) => {
  test.skip(testInfo.project.name !== 'chromium-desktop', 'This audit explicitly exercises every viewport.');
  test.setTimeout(120_000);
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript(({ key, value }) => localStorage.setItem(key, value), { key: STORAGE_KEY, value: serializedEastHarlemDisabilityProject() });
  await page.goto('/');
  await page.getByRole('textbox', { name: 'Class code' }).fill('101');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('article', { name: 'East Harlem disability resources' }).getByRole('button', { name: 'Open project' }).click();
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    const canvas = page.locator('.canvas-wrap');
    const before = await canvas.boundingBox();
    expect(before.width).toBeGreaterThan(width * .9);
    expect(before.height).toBeGreaterThan(900 * .58);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight + 1)).toBe(true);
    await page.getByRole('button', { name: 'Show sidebar', exact: true }).click();
    const inspector = page.locator('#map-inspector');
    const handle = page.getByRole('separator', { name: 'Resize sidebar' });
    await expect(inspector).toBeVisible();
    await handle.press('Home');
    const initial = Number(await handle.getAttribute('aria-valuenow'));
    await handle.press('ArrowLeft');
    expect(Number(await handle.getAttribute('aria-valuenow'))).toBeGreaterThanOrEqual(initial);
    const box = await handle.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down();
    await page.mouse.move(box.x + 65, box.y + box.height / 2, { steps: 4 });
    await page.mouse.up();
    expect(Number(await handle.getAttribute('aria-valuenow'))).toBeLessThanOrEqual(initial);
    if (width <= 1100) expect((await canvas.boundingBox()).width).toBeCloseTo(before.width, 0);
    else expect((await inspector.boundingBox()).width).toBeLessThan(350);
    await page.getByRole('tab', { name: 'Review', exact: true }).click();
    const exports = inspector.locator('.export-dropdown');
    await expect(exports).not.toHaveAttribute('open', '');
    await exports.locator('summary').click();
    await expect(exports.getByRole('button', { name: /JSON Reopen/ })).toBeVisible();
    expect(await inspector.locator('.inspector__scroll').evaluate((el) => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    assertNoAccessibilityViolations(await scanAccessibility(page, makeAxeBuilder, testInfo, `Sidebar at ${width}px`));
    await captureSourceRenderedScreenshot(page, testInfo, `Sidebar at ${width}px`);
    await page.getByRole('button', { name: 'Hide sidebar', exact: true }).click();
    await expect(inspector).not.toBeVisible();
    expect((await canvas.boundingBox()).width).toBeCloseTo(before.width, 0);
    await captureSourceRenderedScreenshot(page, testInfo, `Map at ${width}px`);
    await page.locator('[data-graph-id="node_e2e_home_setting"]').press('Enter');
    await expect(inspector.getByRole('heading', { name: 'Apartment building', exact: true })).toBeInViewport();
    await expect(inspector.getByText('Explain why this item matters to your inquiry.', { exact: false })).toBeVisible();
    await expect(inspector.getByRole('textbox', { name: 'Your interpretation', exact: true })).toBeVisible();
    await expect(inspector.getByRole('button', { name: 'Remove from map', exact: true })).not.toBeVisible();
    expect(await inspector.locator('.inspector__scroll').evaluate((el) => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    assertNoAccessibilityViolations(await scanAccessibility(page, makeAxeBuilder, testInfo, `Selected item at ${width}px`));
    await captureSourceRenderedScreenshot(page, testInfo, `Selected item at ${width}px`);
    await page.getByRole('button', { name: 'Hide sidebar', exact: true }).click();
  }
  expect(errors).toEqual([]);
});
